import { createServer } from "node:http";
import { randomBytes, timingSafeEqual, createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { normalizeJob } from "./job-protocol.mjs";
import { createOperator, OperatorError, requireFreshReport } from "./operator.mjs";
const API_VERSION = "1.3.0";
const DEFAULT_PORT = 31337;
const TOKEN_FILE = resolve(".matrix-cloud.env");
const MAX_BODY_BYTES = 512 * 1024;
let remoteApi;
let token;
let jobQueue = Promise.resolve();

function parseToken(text) {
  return text.match(/^MATRIX_GATEWAY_TOKEN=(.+)$/m)?.[1]?.trim();
}

async function loadToken() {
  if (process.env.MATRIX_GATEWAY_TOKEN) return process.env.MATRIX_GATEWAY_TOKEN;
  if (existsSync(TOKEN_FILE)) {
    const savedToken = parseToken(await readFile(TOKEN_FILE, "utf8"));
    if (savedToken) return savedToken;
  }
  const generatedToken = randomBytes(32).toString("base64url");
  await writeFile(TOKEN_FILE, `MATRIX_GATEWAY_TOKEN=${generatedToken}\n`, { encoding: "utf8", mode: 0o600 });
  console.log(`Created private cloud gateway token at ${TOKEN_FILE}`);
  return generatedToken;
}

function json(response, status, value) {
  response.writeHead(status, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" });
  response.end(JSON.stringify(value));
}

function requestToken(request) {
  const authorization = request.headers.authorization;
  if (typeof authorization === "string" && authorization.startsWith("Bearer ")) return authorization.slice(7);
  const headerToken = request.headers["x-matrix-token"];
  return typeof headerToken === "string" ? headerToken : undefined;
}

function authorized(request) {
  const candidate = requestToken(request);
  if (!candidate || !token) return false;
  const expected = Buffer.from(token);
  const received = Buffer.from(candidate);
  return expected.length === received.length && timingSafeEqual(expected, received);
}

function requireRemoteApi(response) {
  if (!remoteApi?.connection?.connected) {
    json(response, 503, { error: "Bitburner is not connected to the local Remote API." });
    return false;
  }
  return true;
}

function validServer(value) {
  return typeof value === "string" && /^[A-Za-z0-9._-]{1,64}$/.test(value);
}

function validFilename(value) {
  return typeof value === "string" && value.length > 0 && value.length <= 240 && !value.includes("\\") && !value.split("/").includes("..");
}

async function readBody(request) {
  const chunks = [];
  let bytes = 0;
  for await (const chunk of request) {
    bytes += chunk.length;
    if (bytes > MAX_BODY_BYTES) throw new Error("Request body is too large.");
    chunks.push(chunk);
  }
  return bytes === 0 ? {} : JSON.parse(Buffer.concat(chunks).toString("utf8"));
}

