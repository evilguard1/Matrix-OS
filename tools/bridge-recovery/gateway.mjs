async function enqueueJob(command) {
  let queued;
  jobQueue = jobQueue.catch(() => undefined).then(async () => {
    const names = (await remoteApi.getFileNames("home")).result;
    let commands = [];
    if (names.some(name => name.replace(/^\/+/, "") === "cloud/commands.json")) {
      commands = JSON.parse((await remoteApi.getFile({server:"home", filename:"/cloud/commands.json"})).result);
      if (!Array.isArray(commands)) throw new Error("Invalid command queue");
    }
    const previous = commands.find(c => c.id === command.id);
    if (previous) {
      if (JSON.stringify([previous.action,previous.script,previous.server,previous.threads,previous.args,previous.resetEpoch]) !== JSON.stringify([command.action,command.script,command.server,command.threads,command.args,command.resetEpoch])) throw new Error("Invalid idempotency conflict");
      queued = previous; return;
    }
    const now = Date.now();
    commands = commands.filter(c => c.schemaVersion === 2 && c.expiresAt > now && c.resetEpoch === command.resetEpoch);
    if (commands.length >= 100) throw new Error("Command queue full; retry after expiry");
    commands.push(command);
    await remoteApi.pushFile({server:"home",filename:"/cloud/commands.json",content:JSON.stringify(commands)});
    queued = command;
  });
  await jobQueue;
  return queued;
}

export function setRemoteApi(api) {
  remoteApi = api;
  console.log("Bitburner Remote API connected; cloud gateway is ready.");
}

export async function startGateway({ port = Number(process.env.MATRIX_GATEWAY_PORT ?? DEFAULT_PORT) } = {}) {
  token = await loadToken();
  const operator = createOperator({secret:token,enqueue:enqueueJob,
    readRam:async filename=>(await remoteApi.calculateRAM({filename,server:"home"})).result,
    readJson:async (filename,...fallback)=>{
      if (fallback.length) {
        const names=(await remoteApi.getFileNames("home")).result;
        if (!names.some(name=>name.replace(/^\/+/,"")===filename.replace(/^\/+/,""))) return fallback[0];
      }
      return JSON.parse((await remoteApi.getFile({server:"home",filename})).result);
    }});
  const server = createServer(async (request, response) => {
    const url = new URL(request.url ?? "/", "http://127.0.0.1");
    const isSpec = request.method === "GET" && url.pathname === "/openapi.json";
    if (!isSpec && !authorized(request)) return json(response, 401, { error: "Use Authorization: Bearer <MATRIX_GATEWAY_TOKEN>." });
    try {
      if (isSpec) {
        const protocol = process.env.MATRIX_GATEWAY_PUBLIC_URL ? undefined : request.headers["x-forwarded-proto"] ?? "http";
        const publicUrl = process.env.MATRIX_GATEWAY_PUBLIC_URL ?? `${protocol}://${request.headers.host}`;
        return json(response, 200, openApiDocument(publicUrl));
      }
      if (request.method === "GET" && url.pathname === "/v1/status") return json(response, 200, { version: API_VERSION, bitburnerConnected: Boolean(remoteApi?.connection?.connected), commandAgent: "/cloud/agent.js" });
      if (!requireRemoteApi(response)) return;
      if (request.method === "GET" && url.pathname === "/v1/operator/briefing") return json(response,200,await operator.briefing());
      if (request.method === "POST" && url.pathname === "/v1/operator/commands") return json(response,202,await operator.submit(await readBody(request)));
      if (request.method === "GET" && url.pathname === "/v1/operator/receipt") return json(response,200,await operator.receipt(url.searchParams.get("id"),url.searchParams.get("resetEpoch")));
      if (request.method === "GET" && url.pathname === "/v1/agent") {
        const heartbeat = JSON.parse((await remoteApi.getFile({server:"home",filename:"/cloud/heartbeat.txt"})).result);
        return json(response, 200, { ...heartbeat, fresh: Number.isFinite(heartbeat.updated) && heartbeat.updated <= Date.now() && Date.now()-heartbeat.updated < 10000 });
      }
      if (request.method === "GET" && url.pathname === "/v1/jobs") {
        const journal = JSON.parse((await remoteApi.getFile({server:"home",filename:"/cloud/agent-journal.txt"})).result);
        return json(response, 200, journal);
      }
      if (request.method === "GET" && url.pathname === "/v1/briefing") {
        const report = JSON.parse((await remoteApi.getFile({server:"home",filename:"/matrix/state/briefing.txt"})).result);
        const heartbeat = JSON.parse((await remoteApi.getFile({server:"home",filename:"/cloud/heartbeat.txt"})).result);
        requireFreshReport(report,heartbeat);
        return json(response, 200, report);
      }
      if (request.method === "GET" && url.pathname === "/v1/servers") return json(response, 200, { servers: (await remoteApi.getAllServers()).result });
      if (request.method === "GET" && url.pathname === "/v1/files") {
        const serverName = url.searchParams.get("server");
        if (!validServer(serverName)) throw new Error("A valid server query parameter is required.");
        return json(response, 200, { server: serverName, files: (await remoteApi.getFileNames(serverName)).result });
      }
      if (request.method === "GET" && url.pathname === "/v1/ram") {
        const serverName = url.searchParams.get("server") ?? "home";
        const filename = url.searchParams.get("path");
        if (!validServer(serverName) || !validFilename(filename)) throw new Error("Valid server and path query parameters are required.");
        const reply = await remoteApi.calculateRAM({ filename, server: serverName });
        return json(response, 200, { server: serverName, path: filename, ram: reply.result });
      }
      if (request.method === "GET" && url.pathname === "/v1/file") {
        const serverName = url.searchParams.get("server");
        const filename = url.searchParams.get("path");
        if (!validServer(serverName) || !validFilename(filename)) throw new Error("Valid server and path query parameters are required.");
        return json(response, 200, { server: serverName, path: filename, content: (await remoteApi.getFile({ server: serverName, filename })).result });
      }
      if (request.method === "PUT" && url.pathname === "/v1/file") {
        const { server: serverName, path: filename, content } = await readBody(request);
        if (!validServer(serverName) || !validFilename(filename) || typeof content !== "string") throw new Error("server, path, and string content are required.");
        return json(response, 200, { result: (await remoteApi.pushFile({ server: serverName, filename, content })).result });
      }
      if (request.method === "DELETE" && url.pathname === "/v1/file") {
        const serverName = url.searchParams.get("server");
        const filename = url.searchParams.get("path");
        if (!validServer(serverName) || !validFilename(filename)) throw new Error("Valid server and path query parameters are required.");
        return json(response, 200, { result: (await remoteApi.deleteFile({ server: serverName, filename })).result });
      }
      if (request.method === "POST" && url.pathname === "/v1/jobs") {
        const job = await readBody(request);
        const heartbeat = JSON.parse((await remoteApi.getFile({server:"home",filename:"/cloud/heartbeat.txt"})).result);
        const normalized = normalizeJob(job, heartbeat);
        const id = job.idempotencyKey ? createHash("sha256").update(`${heartbeat.resetEpoch}:${job.idempotencyKey}`).digest("hex") : randomBytes(12).toString("hex");
        const command = { ...normalized, id, createdAt: new Date().toISOString() };
        const queued = await enqueueJob(command);
        return json(response, 202, { queued: true, id: queued.id, commandFile: "/cloud/commands.json" });
      }
      return json(response, 404, { error: "Unknown endpoint." });
    } catch (error) {
      if (error instanceof OperatorError) return json(response,error.status,{error:error.message});
      const message = error instanceof Error ? error.message : String(error?.error ?? error ?? "Unexpected gateway error");
      const invalidRequest = message.includes("too large") || message.includes("JSON") || message.includes("required") || message.startsWith("Invalid") || message.startsWith("action") || message.startsWith("threads") || message.startsWith("args");
      return json(response, invalidRequest ? 400 : 502, { error: message });
    }
  });
  await new Promise((resolveStart, rejectStart) => server.once("error", rejectStart).listen(port, "127.0.0.1", resolveStart));
  console.log(`Cloud gateway listening privately at http://127.0.0.1:${port}`);
  return server;
}

if (process.argv.includes("--print-token")) {
  token = await loadToken();
  console.log(token);
  process.exit(0);
}
